class BandType(Enum):
    T_24GHZ = auto()
    T_50GHZ = auto()

class SSID:
    def __init__(self, name: str, mac_addr: str, band_type: BandType):
        self.name = name
        self.mac_addr = mac_addr
        self.band_type = band_type
        self.channel = None
        self.clients = []

    def add_channel(self, channel: int):
        self.channel = channel

def print_info(msg: str, **kwargs):
    print(f"[*] {msg}", **kwargs)

def print_error(msg: str):
    print(f"{RED}[!] {msg}{RESET}")

def print_cmd(msg: str):
    print(f"[>] {msg}")

def print_input(msg: str) -> str:
    return input(f"[?] {msg} ")

def printf(msg: str, **kwargs):
    print(msg, **kwargs)

def restore_print():
    sys.stdout = sys.__stdout__

def invalidate_print():
    pass

def frequency_to_channel(freq):
    if freq <= 2484:
        return (freq - 2407) // 5
    return (freq - 5000) // 5 